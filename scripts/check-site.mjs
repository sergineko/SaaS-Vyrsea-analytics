import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const html=readFileSync('dist/index.html','utf8');
assert.equal((html.match(/<h1\b/g)??[]).length,1,'A single descriptive H1 is required');
assert.ok(html.includes('1 dominio')&&html.includes('2 monitores'),'Free limits must be present without JavaScript');
assert.ok(html.includes('https://vyrsea.com/'),'Canonical Vyrsea domain is required');
assert.ok(!html.includes('PULSO'),'Old brand in HTML');
const json=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]??'{}');
assert.ok(json['@graph']?.some(item=>item['@type']==='WebApplication'));
const app=json['@graph'].find(item=>item['@type']==='WebApplication');assert.equal(app.offers.price,'0');
assert.ok(app.offers.description.includes('15 minutos')&&app.offers.description.includes('7 días'));
for(const plan of ['Free','Starter','Pro / Agencia','Business'])assert.ok(html.includes(`<h3>${plan}</h3>`),`Missing plan ${plan}`);
assert.ok(html.includes('29,99')&&html.includes('Consultar precios')&&html.includes('100'));
assert.ok(html.includes('href="/?demo=pro"')&&html.includes('href="/?demo=business"'),'Advanced demos must be discoverable without JavaScript');
assert.ok(html.includes('2 dominios + 15 monitores')&&html.includes('máximos independientes'),'Independent maximum quotas must be explicit');
assert.ok(html.includes('aprobación manual')&&html.includes('14 días'),'Beta approval and inactivity policy must be public without JavaScript');
assert.ok(readFileSync('dist/robots.txt','utf8').includes('Disallow: /api/'));
assert.ok(readFileSync('dist/sitemap.xml','utf8').includes('<loc>https://vyrsea.com/</loc>'));
assert.ok(readFileSync('dist/llms.txt','utf8').includes('No hay pagos ni correos activos'));
const api=JSON.parse(readFileSync('dist/openapi.json','utf8'));assert.ok(api.paths['/api/dashboard'].get.security);
assert.ok(readFileSync('dist/404.html','utf8').includes('noindex,follow'));
assert.equal(JSON.parse(readFileSync('wrangler.jsonc','utf8')).assets.not_found_handling,'404-page');
console.log('Verificados HTML sin JavaScript, marca, cuotas, canonical, JSON-LD, robots, sitemap, 404 y documentación para agentes.');
